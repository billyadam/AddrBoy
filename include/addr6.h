static_assert(sizeof(columns) / 5 == sizeof(characters) - 1);
inline const uint8_t* glyph(char c)
{
    static uint8_t rows[7];
    unsigned index = 0;
    while (characters[index] && characters[index] != c)
        ++index;
    if (!characters[index])
        index = sizeof(characters) - 2;
    for (int row = 0; row < 7; ++row)
    {
        rows[row] = 0;
        for (int col = 0; col < 5; ++col)
            if ((columns[index][col] >> row) & 1)
                rows[row] |= uint8_t(1 << col);
    }
    return rows;
}
